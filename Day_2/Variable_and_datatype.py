# 1. Storing data in variables using different data types
user_name = "Alex"          # String (text)
user_age = 24               # Integer (whole number)
user_height = 5.11          # Float (decimal number)
is_programmer = True        # Boolean (True/False value)

# 2. Outputting variables and checking their types
print("--- User Profile ---")
print("Name:", user_name, "| Type:", type(user_name))
print("Age:", user_age, "| Type:", type(user_age))
print("Height:", user_height, "| Type:", type(user_height))
print("Codes Python?:", is_programmer, "| Type:", type(is_programmer))
